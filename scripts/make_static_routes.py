"""Give every sitemap URL a real index.html so GitHub Pages returns HTTP 200.

GitHub Pages has no URL rewriting. Its 404.html trick works in a browser but
the server still sends a 404 status, which Google refuses to index. Copying
the built SPA shell into <route>/index.html fixes the status code; React
Router still renders the right page, and trailing slashes match its routes.

Called automatically by Update LocalTech Website.bat after npm run build.
Run manually with:  python scripts/make_static_routes.py
"""
import os
import re
import shutil
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
SITEMAP = ROOT / "public" / "sitemap.xml"
MANIFEST = ROOT / "generated-routes.txt"
BASE = "https://localtechza.co.za"
NS = "{http://www.sitemaps.org/schemas/sitemap/0.9}"

index_file = BUILD / "index.html"
if not index_file.exists():
    raise SystemExit("build/index.html not found — run npm run build first")

shell = index_file.read_text(encoding="utf-8")

# Remove folders generated by an earlier deploy so deleted products do not
# leave live, orphaned pages behind. The manifest keeps this list exact.
if MANIFEST.exists():
    for rel in MANIFEST.read_text(encoding="utf-8").splitlines():
        rel = rel.strip()
        if not rel or rel.startswith("/") or ".." in rel.split("/"):
            continue  # safety: never delete outside the project
        target = ROOT / rel
        if target.is_dir():
            shutil.rmtree(target)

tree = ET.parse(str(SITEMAP))
written = []
for loc in tree.findall(".//" + NS + "loc"):
    url = (loc.text or "").strip()
    if not url.startswith(BASE):
        continue
    rel = url[len(BASE):].strip("/")
    if not rel:
        continue  # the homepage is build/index.html itself

    # A per-page canonical keeps /about/ as the indexed URL even though
    # in-app links use /about. Replace any canonical from the root shell.
    page = re.sub(r'<link rel="canonical"[^>]*>', "", shell)
    canonical = f'<link rel="canonical" href="{BASE}/{rel}/" />'
    page = page.replace("</head>", "    " + canonical + "</head>")

    dest = BUILD / rel
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "index.html").write_text(page, encoding="utf-8")
    written.append(rel)

MANIFEST.write_text("\n".join(written) + "\n", encoding="utf-8")
print(f"created {len(written)} real route pages in build/")
print(f"  e.g. {written[0] if written else '(none)'}/index.html")
